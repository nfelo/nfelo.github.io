#!/usr/bin/env bash
set -Eeuo pipefail
BASE_CODE="42e227462421b2372fa3640d0ac9b42606e6414f"
SELF="$(basename "$0")"
NO_PUSH=false
[ "${1:-}" = "--no-push" ] && NO_PUSH=true
TARGETS=(config/club_model.json public/clubs/clubs.css public/clubs/clubs.js public/clubs/index.html scripts/build_site.py scripts/club_ledger.py scripts/club_model.py tests/test_club_section.py)
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
note() { printf '\n==> %s\n' "$*"; }
git rev-parse --show-toplevel >/dev/null 2>&1 || die "Run this from the nfelo.github.io repository root."
[ -f scripts/build_site.py ] || die "This is not the NFELO repository root."
note "Checking compatibility (routine data-refresh commits are supported)"
git fetch --quiet origin main
if ! git cat-file -e "$BASE_CODE^{commit}" 2>/dev/null; then
  note "The Codespace checkout is shallow; fetching enough history for the compatibility check"
  if [ "$(git rev-parse --is-shallow-repository)" = "true" ]; then
    git fetch --quiet --deepen=100 origin main ||
      git fetch --quiet --unshallow origin main
  fi
fi
if ! git cat-file -e "$BASE_CODE^{commit}" 2>/dev/null; then
  # GitHub permits fetching a reachable commit directly even when a hosting
  # environment has configured an unusually narrow partial clone.
  git fetch --quiet origin "$BASE_CODE" || true
fi
git cat-file -e "$BASE_CODE^{commit}" 2>/dev/null ||
  die "Could not retrieve the supported base commit from origin."
git merge-base --is-ancestor "$BASE_CODE" HEAD || die "The repository does not descend from the supported club release."
git diff --quiet "$BASE_CODE" HEAD -- "${TARGETS[@]}" || die "Club code has overlapping edits. Data-only refreshes are accepted; code edits require a fresh installer."
unexpected="$(git status --porcelain | awk -v self="$SELF" 'substr($0,4) != self {print}')"
[ -z "$unexpected" ] || { printf '%s\n' "$unexpected" >&2; die "Resolve the changes above first."; }
PATCH_FILE="$(mktemp)"
trap 'rm -f "$PATCH_FILE"' EXIT
awk '/^__PAYLOAD_BEGIN__$/ {read=1; next} /^__PAYLOAD_END__$/ {exit} read' "$0" | base64 --decode | gzip --decompress > "$PATCH_FILE"
git apply --check "$PATCH_FILE"
git apply "$PATCH_FILE"
note "Installing the isolated club-build runtime"
python3 -m venv .club-install-venv
.club-install-venv/bin/python -m pip install --upgrade pip
.club-install-venv/bin/python -m pip install --requirement requirements.txt
.club-install-venv/bin/python -m pip check
note "Replaying and exporting the independent global club model"
.club-install-venv/bin/python scripts/build_club_site.py --source source --config config --output public --cache .club-cache
note "Validating the update-safe snapshot and browser contract"
.club-install-venv/bin/python - <<'PY'
import sys
from pathlib import Path
sys.path.insert(0, "scripts")
from build_site import validate_prebuilt_club_site
meta = validate_prebuilt_club_site(Path("public"))
print(f"Validated {meta['rated_clubs']:,} clubs and {meta['matches']:,} matches.")
PY
.club-install-venv/bin/python -m unittest tests.test_club_section --verbose
node --check public/clubs/clubs.js
git diff --check
note "Staging the implementation and generated archive"
git add -- "${TARGETS[@]}" public/clubs public/index.html public/sitemap.xml
if git ls-files --error-unmatch "$SELF" >/dev/null 2>&1; then git rm -- "$SELF"; else rm -f -- "$SELF"; fi
git config user.name >/dev/null 2>&1 || git config user.name "NFELO installer"
git config user.email >/dev/null 2>&1 || git config user.email "installer@users.noreply.github.com"
git commit -m "feat: rebuild global club rankings v3"
if [ "$NO_PUSH" = false ]; then note "Pushing the validated installation to main"; git push origin HEAD:main; else note "Committed locally; --no-push left the commit for review"; fi
note "Done. National data refreshes validate and preserve this snapshot without rerunning the heavyweight club replay."
exit 0
